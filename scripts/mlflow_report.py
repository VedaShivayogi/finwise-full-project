"""Regenerates the experiment evidence straight from MLflow so documentation can never drift from the logged runs.

    python scripts/mlflow_report.py [--db sqlite:///mlflow.db]
Writes  reports/mlflow_runs.csv  (every run: parameters + metrics)  and  experiment_report.md.
Read-only on the MLflow database.   Optional: run scripts/cv_check.py first to include the cross-validation table."""
import argparse, json
from pathlib import Path
import mlflow, pandas as pd

ROOT = Path(__file__).resolve().parent.parent
ap = argparse.ArgumentParser(); ap.add_argument("--db", default="sqlite:///mlflow.db"); a = ap.parse_args()
mlflow.set_tracking_uri(a.db)
EXP = "finwise_champion_model"
df = mlflow.search_runs(experiment_names=[EXP], filter_string="status = 'FINISHED'")
assert len(df) >= 2, "need at least 2 finished runs"
df = df.rename(columns={"tags.mlflow.runName": "run_name"})
meta = json.load(open(ROOT / "artifacts/champion_model_metadata.json"))
sel = df.sort_values("metrics.val_gini", ascending=False).reset_index(drop=True)
best = sel.iloc[0]
assert best["run_id"] == meta["mlflow_run_id"], "champion in artifacts is not the best run in MLflow"

keep = ["run_id", "run_name"] + [c for c in df.columns if c.startswith(("params.", "metrics."))]
(ROOT / "reports").mkdir(exist_ok=True)
df[keep].sort_values("run_name").to_csv(ROOT / "reports/mlflow_runs.csv", index=False)

PK = ["n_estimators", "max_depth", "learning_rate", "subsample", "colsample_bytree", "min_child_weight", "gamma",
      "reg_alpha", "reg_lambda", "scale_pos_weight"]
def pv(r, k):
    v = r.get(f"params.{k}"); 
    if not isinstance(v, str): return "-"
    f = float(v); return f"{f:g}" if k != "scale_pos_weight" else f"{f:.2f}"
ptab = "| Parameter | " + " | ".join(sel.run_name.str.replace("config_", "")) + " |\n|---|" + "---|" * len(sel) + "\n"
ptab += "\n".join(f"| `{k}` | " + " | ".join(pv(r, k) for _, r in sel.iterrows()) + " |" for k in PK)

def m(r, k): return r[f"metrics.{k}"]
rtab = ("| Config | Trees used | Val Gini | Val AUC | Test Gini | Test AUC | Test KS | Test Brier | Train-Val Gini gap |\n|---|---|---|---|---|---|---|---|---|\n")
for _, r in sel.iterrows():
    star = " **(selected)**" if r.run_id == best.run_id else ""
    rtab += (f"| {r.run_name}{star} | {int(m(r,'best_iteration'))+1} | {m(r,'val_gini'):.4f} | {m(r,'val_auc'):.4f} | {m(r,'test_gini'):.4f} | "
             f"{m(r,'test_auc'):.4f} | {m(r,'test_ks_statistic'):.4f} | {m(r,'test_brier_score'):.4f} | {m(r,'train_gini')-m(r,'val_gini'):.4f} |\n")

runner = sel.iloc[1]
top_test = sel.sort_values('metrics.test_gini', ascending=False).iloc[0]
low_gap = sel.assign(g=sel['metrics.train_gini'] - sel['metrics.val_gini']).sort_values('g').iloc[0]
margin = m(best, "val_gini") - m(runner, "val_gini")
cvf = ROOT / "reports/cv_check.csv"
if cvf.exists():
    cv = pd.read_csv(cvf)
    ctab = "| Config | CV Gini (mean) | Std across folds | Trees |\n|---|---|---|---|\n" + "\n".join(
        f"| {r.run_name} | {r.cv_gini_mean:.4f} | {r.cv_gini_std:.4f} | {r.trees} |" for _, r in cv.iterrows())
    spread = cv.cv_gini_mean.max() - cv.cv_gini_mean.min()
    cv_text = (f"\n### Cross-validation check (supplementary, not part of the MLflow selection)\n"
               f"The validation set has only {meta['metrics']['val']['n']} rows, so I also ran 5-fold stratified cross-validation on train + validation "
               f"({meta['metrics']['train']['n'] + meta['metrics']['val']['n']} rows, test set untouched) using each run's logged hyperparameters "
               f"(`scripts/cv_check.py`).\n\n{ctab}\n\n"
               f"The three configurations are within **{spread:.3f}** Gini of each other, far smaller than the fold-to-fold standard deviation "
               f"(about {cv.cv_gini_std.mean():.3f}). **Conclusion: the configurations are statistically indistinguishable on this dataset.**\n")
else:
    cv_text = ""; spread = None

tm = meta["metrics"]["test"]
md = f"""# Core model and experimentation report

**Experiment tracking:** MLflow, experiment `{EXP}`, store `sqlite:///mlflow.db` ({len(sel)} finished runs, all in `reports/mlflow_runs.csv`).
**Primary model:** XGBoost classifier. **Hyperparameter configurations compared:** {len(sel)}.
**Best configuration:** `{best.run_name}`, MLflow run `{best.run_id}`.
**Generated by:** `scripts/mlflow_report.py` straight from the MLflow database, so these numbers are the logged ones.

## 1. Result in one paragraph
Three XGBoost configurations were trained and logged to MLflow (parameters, train/validation/test metrics, best iteration, model).
The selection rule used is *highest validation Gini* (the test set plays no part in the choice). `{best.run_name}` won with validation Gini
**{m(best,'val_gini'):.4f}** and, on the untouched test set, reached **Gini {tm['gini']:.4f}** (AUC {tm['auc']:.4f}), which meets the project target of
{meta['target_gini']} or higher. The logistic-regression baseline scores {meta['baseline_test_gini']:.3f} on the same test set, so the champion does **not** beat the baseline; both pass the target.

## 2. How to see the experiments
```bash
mlflow ui --backend-store-uri sqlite:///mlflow.db        # then open http://127.0.0.1:5000  and choose experiment "{EXP}"
```
Screenshots: `docs/mlflow_ui_runs.png` (run list) and `docs/mlflow_ui_compare.png` (side-by-side comparison).
![MLflow runs](docs/mlflow_ui_runs.png)

## 3. Configurations tested (logged parameters)
{ptab}

All three use early stopping (30 rounds on validation AUC) and `scale_pos_weight` for the class imbalance; `n_estimators` is a ceiling, and the trees actually used are shown below.

## 4. Results (logged metrics)
Split: {meta['metrics']['train']['n']} train / {meta['metrics']['val']['n']} validation / {meta['metrics']['test']['n']} test (stratified, seed 42).

{rtab}
Train-Val gap = train Gini minus validation Gini (overfitting signal). Figures: `experiment_roc_comparison.png`, `experiment_metric_comparison.png`.
![ROC comparison](experiment_roc_comparison.png)

## 5. Best configuration and the evidence for it
**Selected: `{best.run_name}`**

| Evidence | Value |
|---|---|
| Selection metric (validation Gini) | **{m(best,'val_gini'):.4f}**, highest of {len(sel)} runs (runner-up `{runner.run_name}` {m(runner,'val_gini'):.4f}) |
| Final test Gini (held out from selection) | {tm['gini']:.4f} (target {meta['target_gini']}: **met**) |
| Test AUC / KS / Brier | {tm['auc']:.4f} / {m(best,'test_ks_statistic'):.4f} / {m(best,'test_brier_score'):.4f} |
| Early stopping | best iteration {int(m(best,'best_iteration'))}, {int(m(best,'best_iteration'))+1} trees used |
| Baseline (logistic regression) test Gini | {meta['baseline_test_gini']:.4f} |
{cv_text}
### Honest reading of the evidence
- The winning margin on validation is **{margin:.4f} Gini on {meta['metrics']['val']['n']} rows, which is within noise**. `{best.run_name}` is the winner because it satisfies the selection rule (highest validation Gini),
  not because it is clearly better.
- On the test set the highest Gini belongs to `{top_test.run_name}` ({m(top_test,'test_gini'):.4f}){"" if top_test.run_id == best.run_id else ", not to the selected run"}. That is *expected* from noise with about 48 defaulters in the test set, and the test set was **deliberately not used to re-pick**:
  choosing a configuration after seeing test results would make the reported test score optimistic.
- The selected run's train-to-validation Gini gap is {m(best,'train_gini')-m(best,'val_gini'):.3f}; the smallest gap (least overfitting) is `{low_gap.run_name}` at {m(low_gap,'train_gini')-m(low_gap,'val_gini'):.3f}, a reasonable alternative if simplicity or overfitting matters more.
  Next step: a wider search (for example Optuna or random search with cross-validation) on more, real data.

## 6. Reproduce
```bash
python core_model_experimentation.py              # trains the 3 configs and logs them to MLflow (sqlite:///mlflow.db)
python scripts/cv_check.py                        # supplementary 5-fold CV
python scripts/mlflow_report.py                   # regenerates this report and reports/mlflow_runs.csv
mlflow ui --backend-store-uri sqlite:///mlflow.db
```
"""
(ROOT / "experiment_report.md").write_text(md)
print("wrote experiment_report.md and reports/mlflow_runs.csv; best =", best.run_name)
